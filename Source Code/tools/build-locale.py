"""Validate the single keyed resource source and emit compact C tables."""
import json, re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
def unique(pairs):
    result = {}
    for k, v in pairs:
        if k in result: raise ValueError('Duplicate property: ' + k)
        result[k] = v
    return result
def load(name):
    return json.loads((root/'resources/locale'/name).read_text(encoding='utf-8'), object_pairs_hook=unique)
catalog = load('catalog.json')
languages = [load('zh-CN.json'), load('en-US.json')]
keys = [row['key'] for row in catalog]
if len(set(keys)) != len(keys): raise ValueError('Duplicate resource key')
for row in catalog:
    k = row['key']
    if not re.fullmatch(r'[A-Z][A-Z0-9_]+', k) or not k.startswith(row['module']+'_'+row['type']+'_'):
        raise ValueError('Invalid resource key: '+k)
    if row['type'] not in ['TITLE','LABEL','ACTION','STATUS','ERROR','HELP','TEMPLATE']:
        raise ValueError('Invalid resource type: '+k)
    if len(set(row['parameters'])) != len(row['parameters']) or not set(row['parameters']) <= {'name','count'}:
        raise ValueError('Unsupported or duplicate parameter: '+k)
    for lang in languages:
        if set(lang) != set(keys): raise ValueError('Missing or extra language keys')
        text = lang[k]
        if not isinstance(text,str) or '\0' in text: raise ValueError('Invalid text: '+k)
        text.encode('utf-8')
        if set(re.findall(r'\{([a-z]+)\}',text)) != set(row['parameters']):
            raise ValueError('Template parameter mismatch: '+k)
header = '/* Generated by tools/build-locale.py; edit resources/locale instead. */\n'
(root/'src32/locale_keys.h').write_text(header+'typedef enum {\n  TEXT_NONE = 0,\n'+''.join('  '+k+',\n' for k in keys)+'  TEXT_KEY_COUNT\n} TextKey;\n',encoding='utf-8')
quote = lambda text: json.dumps(text,ensure_ascii=False)
(root/'src32/locale_data.inc').write_text(header+'static const char *const resources[TEXT_KEY_COUNT][2] = {\n  {"", ""},\n'+''.join('  {'+', '.join(quote(lang[k]) for lang in languages)+'},\n' for k in keys)+'};\n',encoding='utf-8')
print('Validated and generated', len(keys), 'bilingual resources')
